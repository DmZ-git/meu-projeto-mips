library IEEE;
use IEEE.STD_LOGIC_1164.ALL;
use IEEE.NUMERIC_STD.ALL;

entity ula is
    Port (
        A      : in  STD_LOGIC_VECTOR(31 downto 0);
        B      : in  STD_LOGIC_VECTOR(31 downto 0);
        shamt  : in  STD_LOGIC_VECTOR(4 downto 0);
        funct  : in  STD_LOGIC_VECTOR(5 downto 0);

        R      : out STD_LOGIC_VECTOR(31 downto 0);

        zero   : out STD_LOGIC;
        ovfl   : out STD_LOGIC
    );
end ula;

architecture rtl of ula is
begin

process(A,B,funct,shamt)

    variable temp33 : SIGNED(32 downto 0);
    variable res32  : STD_LOGIC_VECTOR(31 downto 0);

begin

    res32 := (others => '0');
    ovfl  <= '0';

    case funct is

    ----------------------------------------------------------------
    -- ADD
    ----------------------------------------------------------------
    when "100000" =>

        temp33 := ('0' & signed(A)) +
                  ('0' & signed(B));

        res32 := std_logic_vector(temp33(31 downto 0));

        if (A(31)=B(31)) and
           (res32(31)/=A(31)) then
            ovfl <= '1';
        end if;

    ----------------------------------------------------------------
    -- ADDU
    ----------------------------------------------------------------
    when "100001" =>

        res32 := std_logic_vector(
                 unsigned(A)+unsigned(B));

    ----------------------------------------------------------------
    -- SUB
    ----------------------------------------------------------------
    when "100010" =>

        temp33 := ('0' & signed(A)) -
                  ('0' & signed(B));

        res32 := std_logic_vector(temp33(31 downto 0));

        if (A(31)/=B(31)) and
           (res32(31)/=A(31)) then
            ovfl <= '1';
        end if;

    ----------------------------------------------------------------
    -- SUBU
    ----------------------------------------------------------------
    when "100011" =>

        res32 := std_logic_vector(
                 unsigned(A)-unsigned(B));

    ----------------------------------------------------------------
    -- AND
    ----------------------------------------------------------------
    when "100100" =>

        res32 := A and B;

    ----------------------------------------------------------------
    -- OR
    ----------------------------------------------------------------
    when "100101" =>

        res32 := A or B;

    ----------------------------------------------------------------
    -- XOR
    ----------------------------------------------------------------
    when "100110" =>

        res32 := A xor B;

    ----------------------------------------------------------------
    -- NOR
    ----------------------------------------------------------------
    when "100111" =>

        res32 := not(A or B);

    ----------------------------------------------------------------
    -- SLT
    ----------------------------------------------------------------
    when "101010" =>

        if signed(A) < signed(B) then
            res32 := x"00000001";
        else
            res32 := x"00000000";
        end if;

    ----------------------------------------------------------------
    -- SLTU
    ----------------------------------------------------------------
    when "101011" =>

        if unsigned(A) < unsigned(B) then
            res32 := x"00000001";
        else
            res32 := x"00000000";
        end if;

    ----------------------------------------------------------------
    -- SLL
    ----------------------------------------------------------------
    when "000000" =>

        res32 := std_logic_vector(
                 shift_left(
                 unsigned(B),
                 to_integer(unsigned(shamt))));

    ----------------------------------------------------------------
    -- SRL
    ----------------------------------------------------------------
    when "000010" =>

        res32 := std_logic_vector(
                 shift_right(
                 unsigned(B),
                 to_integer(unsigned(shamt))));

    ----------------------------------------------------------------
    -- SRA
    ----------------------------------------------------------------
    when "000011" =>

        res32 := std_logic_vector(
                 shift_right(
                 signed(B),
                 to_integer(unsigned(shamt))));

    ----------------------------------------------------------------
    -- DEFAULT
    ----------------------------------------------------------------
    when others =>

        res32 := (others => '0');

    end case;

    R <= res32;

    if res32 = x"00000000" then
        zero <= '1';
    else
        zero <= '0';
    end if;

end process;

end rtl;